<?php

namespace App\Http\Controllers\Admin;

use App\Http\Controllers\Controller;
use Illuminate\Http\Request;
use RealRashid\SweetAlert\Facades\Alert;
use App\Models\PassportServerCopyType;


class PassportServerCopyTypeController extends Controller
{
    public function index()
    {
        $passportServerCopy = PassportServerCopyType::latest()->get();
        return view('admin.passport_server_copy.passport_server_copy_type', compact('passportServerCopy'));
    }

    /**
     * Show the form for creating a new resource.
     *
     * @return \Illuminate\Http\Response
     */
    public function create()
    {
        //
    }

    /**
     * Store a newly created resource in storage.
     *
     * @param  \Illuminate\Http\Request  $request
     * @return \Illuminate\Http\Response
     */
    public function store(Request $request)
    {
        PassportServerCopyType::create($request->all());
        Alert::toast("Type Created Successfully.", 'success');
        return redirect()->back();
    }

    /**
     * Display the specified resource.
     *
     * @param  int  $id
     * @return \Illuminate\Http\Response
     */
    public function show($id)
    {
        //
    }

    /**
     * Show the form for editing the specified resource.
     *
     * @param  int  $id
     * @return \Illuminate\Http\Response
     */
    public function edit($id)
    {
        //
    }

    /**
     * Update the specified resource in storage.
     *
     * @param  \Illuminate\Http\Request  $request
     * @param  int  $id
     * @return \Illuminate\Http\Response
     */
    public function update(Request $request, $id)
    {

        $passportServerCopy = PassportServerCopyType::find($id);

        $passportServerCopy->update($request->all());
        Alert::toast("Type Updated Successfully.", 'success');
        return redirect()->back();
    }

    /**
     * Remove the specified resource from storage.
     *
     * @param  int  $id
     * @return \Illuminate\Http\Response
     */
    public function destroy($id)
    {
        $entity = PassportServerCopyType::find($id);

        $entity->delete();
        Alert::toast("Type Deleted Successfully.", 'success');
        return redirect()->back();
    }
}
